/**
 * Escapes the five HTML-significant characters so user content cannot break
 * out of text or a quoted attribute when markup is built as a string.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
